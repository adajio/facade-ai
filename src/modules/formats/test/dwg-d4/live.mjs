import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

assert.equal(process.argv.length, 4, "Supply a synthetic D4 control DWG and a new output directory");
const input = resolve(process.argv[2]);
const output = resolve(process.argv[3]);
await mkdir(output, { mode: 0o700 });
process.env.FACADE_DATA_DIR = output;
const dist = resolve(process.env.FACADE_STEP11_DIST ?? "dist");
const { createFormatAdapters } = await import(pathToFileURL(join(dist, "src/modules/formats/index.js")));
const { isOdaDwgVersion } = await import(pathToFileURL(join(dist, "src/modules/formats/dwg-profile.js")));
const adapter = createFormatAdapters().find(({ format }) => format === "dwg");
const readerVersion = await adapter.version();
assert.ok(isOdaDwgVersion(readerVersion), "A pinned ODA broker is required");

const originalSha256 = createHash("sha256").update(await readFile(input)).digest("hex");
const source = { projectId: randomUUID(), documentId: randomUUID(), versionId: randomUUID(), sha256: originalSha256 };
const started = performance.now();
const units = await adapter.inspect(input, source);
const elapsedMs = Math.round(performance.now() - started);
const unit = units.find(({ locator }) => locator.space === "Model");
assert.ok(unit, JSON.stringify(units));
assert.equal(unit.locator.derivativeFormat, "dxf");
const request = { representation: "native", address: { unitId: unit.id } };
const native = await adapter.readCached(source, request, unit, readerVersion);
const data = JSON.parse(native.bytes);
const text = data.lines.find(line => line.text === "D4 POSITIVE | gap 37 mm");
assert.ok(text);
assert.match(text.locator.derivativeHandle, /^[0-9A-F]+$/u);
assert.equal(text.locator.handle, undefined);
const proof = await adapter.durableInfo(source, units, readerVersion);
assert.equal(proof.format, "dxf");
const result = { readerVersion, originalSha256, elapsedMs, proof, units };
await writeFile(join(output, "oda.json"), JSON.stringify(result, null, 2) + "\n");
console.log(JSON.stringify(result, null, 2));
