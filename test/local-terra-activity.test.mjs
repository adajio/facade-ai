import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {mkdtemp, readFile, readdir, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import test from 'node:test';
import pg from 'pg';
import {recordPrimaryActivity} from '../infra/local-terra/activity.mjs';
import {exportActivity} from '../infra/local-terra/export-activity.mjs';

const connectionString=process.env.PRELIMINARY_TEST_DATABASE_URL;
test('operator journal keeps legacy preparations, unknown outcomes and recovered results across exports', {skip:!connectionString}, async t=>{
  const url=new URL(connectionString);
  assert.ok(['localhost','127.0.0.1','[::1]'].includes(url.hostname) && /^\/facade_test_[a-z0-9_]+$/.test(url.pathname));
  const schema='activity_'+randomUUID().replaceAll('-','');
  const admin=new pg.Pool({connectionString});
  await admin.query('CREATE SCHEMA '+schema);
  const db=new pg.Pool({connectionString,options:'-c search_path='+schema+',public'});
  const dir=await mkdtemp(join(tmpdir(),'facade-activity-'));
  t.after(async()=>{
    await db.end();
    await admin.query('DROP SCHEMA '+schema+' CASCADE');
    await admin.end();
    await rm(dir,{recursive:true,force:true});
  });
  const migrations=new URL('../db/migrations/',import.meta.url);
  const names=(await readdir(migrations)).filter(n=>n.endsWith('.sql')&&!n.startsWith('01_')).sort();
  for(const name of names.filter(n=>!n.startsWith('42_'))) await db.query(await readFile(new URL(name,migrations),'utf8'));
  const [org,actor,projectId,receiptId,preparationId]=Array.from({length:5},randomUUID);
  await db.query("INSERT INTO organizations(id,name) VALUES($1,'Example')",[org]);
  await db.query("INSERT INTO users(id,organization_id,login) VALUES($1,$2,'tester')",[actor,org]);
  await db.query("INSERT INTO projects(id,organization_id,name,intake_mode) VALUES($1,$2,'Journal fixture',true)",[projectId,org]);
  await db.query("INSERT INTO intake_receipts(id,project_id,source,created_by,sealed_at) VALUES($1,$2,'upload',$3,now())",[receiptId,projectId,actor]);
  const insertPrep="INSERT INTO intake_package_preparations(id,project_id,receipt_id,revision,snapshot_hash,manifest) VALUES($1,$2,$3,$4,$5,'{}')";
  await db.query(insertPrep,[preparationId,projectId,receiptId,1,'a'.repeat(64)]);
  await db.query(await readFile(new URL('42_project_reading_activity.sql',migrations),'utf8'));
  await db.query(insertPrep,[randomUUID(),projectId,receiptId,2,'b'.repeat(64)]);
  const attempt={projectId,receiptId,preparationId,stage:'primary_review',attemptKey:'example',status:'unknown',reason:'no_response'};
  await recordPrimaryActivity(db,attempt);
  await recordPrimaryActivity(db,attempt);
  await exportActivity(db,dir);
  await recordPrimaryActivity(db,{...attempt,status:'published',reason:null,fields:{inputTokens:123,sourceText:'private-fixture-text'}});
  await exportActivity(db,dir);
  await exportActivity(db,dir);
  const files=(await readdir(join(dir,projectId))).filter(n=>n.endsWith('.jsonl'));
  const records=[];
  for(const file of files) records.push(...(await readFile(join(dir,projectId,file),'utf8')).trim().split('\n').map(JSON.parse));
  assert.equal(records.filter(r=>r.stage==='preparation').length,2);
  assert.deepEqual(records.filter(r=>r.stage==='primary_review').map(r=>r.status),['unknown','published']);
  assert.equal(records.find(r=>r.stage==='primary_review'&&r.status==='published').fields.inputTokens,123);
  assert.ok(!JSON.stringify(records).includes('private-fixture-text'));
  assert.match(await readFile(join(dir,'Все проекты.md'),'utf8'),/Journal fixture/);
});
